"""mkfont.py: a TTF/OTF -> 4-bit anti-aliased bitmap faces for the player's SNRGY themes and the reader.

  python tools/mkfont.py FONT.ttf [--name ui|book] [--px 18 | --px 13,15,18,22] [--out FILE]

--name ui   the SNRGY UI face (homebrew/common/ui_font.h), one size, glyphs centred in Sony's 22 px line
--name book the reader face (book_font.h): one or more sizes (the reader zooms between them with the volume keys),
            each in its own line height (about 1.4 x the size)

Code points 32..255 (ASCII + Latin-1: the Spanish and English UI); characters the font lacks are left out and fall
back to Sony's font. The output is derived from the font you pass, so it is NOT committed (.gitignore): bring your
own font (prototype builds: DIN Alternate Bold for the UI, Georgia for books). Needs Pillow."""
import argparse, os
from PIL import Image, ImageDraw, ImageFont

ap = argparse.ArgumentParser()
ap.add_argument('font')
ap.add_argument('--name', default='ui', help='ui (ui_font.h) or book (book_font.h)')
ap.add_argument('--px', default='18', help='size(s) in pixels, comma separated (book: e.g. 13,15,18,22)')
ap.add_argument('--line', type=int, default=0, help='line height (default: 22 for ui, ~1.4 x the size for book)')
ap.add_argument('--out', default=None)
a = ap.parse_args()
if not a.out: a.out = os.path.join(os.path.dirname(__file__), '..', 'homebrew', 'common', '%s_font.h' % a.name)
U, sizes = a.name.upper(), [int(x) for x in a.px.split(',')]


def face(px, line):
    f = ImageFont.truetype(a.font, px)
    cap_top, cap_bot = f.getbbox('H')[1], f.getbbox('H')[3]
    base_y = (line - (cap_bot - cap_top)) // 2 - cap_top + 1  # where the origin goes so capitals sit centred

    def bitmap(ch):
        l, t, r, b = f.getbbox(ch)
        if r <= l or b <= t: return None
        im = Image.new('L', (r - l, b - t), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
        return im.tobytes()
    notdef = bitmap('￿')
    glyphs, data = [], bytearray()
    for cp in range(32, 256):
        ch = chr(cp)
        if 127 <= cp < 160 or (cp > 32 and notdef is not None and bitmap(ch) == notdef):
            glyphs.append((0, 0, 0, 0, 0, 0)); continue
        adv = int(round(f.getlength(ch)))
        l, t, r, b = f.getbbox(ch)
        w, h = max(0, r - l), max(0, b - t)
        off = len(data)
        if w and h:
            px4 = [v >> 4 for v in bitmap(ch)]
            if len(px4) % 2: px4.append(0)
            data += bytes(px4[i] << 4 | px4[i + 1] for i in range(0, len(px4), 2))
        glyphs.append((adv, l, base_y + t, w, h, off) if w and h else (adv, 0, 0, 0, 0, 0))
    return glyphs, data, cap_bot - cap_top


with open(a.out, 'w') as o:
    o.write('/* generated by tools/mkfont.py from %s at %s px: NOT for the repository (derived from that font) */\n'
            % (os.path.basename(a.font), a.px))
    o.write('#ifndef FONT_GLYPH_T\n#define FONT_GLYPH_T\n'
            '/* per code point 32..255: advance, x / y offset in the line, width, height, data offset (4 bpp, 2 px a byte) */\n'
            'struct font_glyph { signed char adv, x, y; unsigned char w, h; unsigned short off; };\n#endif\n')
    lines = []
    for k, px in enumerate(sizes):
        line = a.line or (22 if a.name == 'ui' else int(round(px * 1.4)))
        lines.append(line)
        glyphs, data, caps = face(px, line)
        o.write('static const struct font_glyph %s_font_g%d[224] = {\n' % (a.name, k))
        for g in glyphs: o.write('\t{ %d, %d, %d, %d, %d, %d },\n' % g)
        o.write('};\nstatic const unsigned char %s_font_px%d[%d] = {\n' % (a.name, k, max(1, len(data))))
        for i in range(0, len(data), 24): o.write('\t' + ', '.join(str(x) for x in data[i:i + 24]) + ',\n')
        o.write('};\n')
        print('%s %d px: line %d, caps %d px, %d bytes' % (a.name, px, line, caps, len(data)))
    n = len(sizes)
    o.write('#define %s_FONT %d	/* sizes */\n' % (U, n))
    o.write('static const struct font_glyph *const %s_font_gs[%d] = { %s };\n' % (a.name, n, ', '.join('%s_font_g%d' % (a.name, k) for k in range(n))))
    o.write('static const unsigned char *const %s_font_pxs[%d] = { %s };\n' % (a.name, n, ', '.join('%s_font_px%d' % (a.name, k) for k in range(n))))
    o.write('static const int %s_font_lines[%d] = { %s };\n' % (a.name, n, ', '.join(str(l) for l in lines)))
print('wrote', a.out)
