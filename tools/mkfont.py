"""mkfont.py: a TTF/OTF -> 4-bit anti-aliased bitmap font for the player's SNRGY themes (common/ui_font.h).

  python tools/mkfont.py FONT.ttf [--px 16] [--out homebrew/common/ui_font.h]

Code points 32..255 (ASCII + Latin-1: the Spanish and English UI). Glyphs are drawn in a 22 px line like Sony's
font, cap height centred. The output is derived from the font you pass, so it is NOT committed (.gitignore): bring
your own font (prototype builds use DIN Alternate Bold). Without the header the themes fall back to Sony's font.
Needs Pillow."""
import argparse, os
from PIL import Image, ImageDraw, ImageFont

ap = argparse.ArgumentParser()
ap.add_argument('font')
ap.add_argument('--px', type=int, default=16, help='font size in pixels (16: caps ~11 px, like the mockups)')
ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'homebrew', 'common', 'ui_font.h'))
a = ap.parse_args()

LINE = 22
f = ImageFont.truetype(a.font, a.px)
cap_top, cap_bot = f.getbbox('H')[1], f.getbbox('H')[3]
base_y = (LINE - (cap_bot - cap_top)) // 2 - cap_top + 1  # y where the font's origin goes so caps are centred
def bitmap(ch):
    l, t, r, b = f.getbbox(ch)
    if r <= l or b <= t: return None
    im = Image.new('L', (r - l, b - t), 0)
    ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
    return im.tobytes()
NOTDEF = bitmap('\uffff')  # what the font draws for a character it lacks: those fall back to Sony's font
glyphs, data = [], bytearray()
for cp in range(32, 256):
    ch = chr(cp)
    if 127 <= cp < 160 or (cp > 32 and NOTDEF is not None and bitmap(ch) == NOTDEF):
        glyphs.append((0, 0, 0, 0, 0)); continue
    adv = int(round(f.getlength(ch)))
    l, t, r, b = f.getbbox(ch)
    w, h = max(0, r - l), max(0, b - t)
    off = len(data)
    if w and h:
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
        px = [v >> 4 for v in im.tobytes()]
        if len(px) % 2: px.append(0)
        data += bytes(px[i] << 4 | px[i + 1] for i in range(0, len(px), 2))
    glyphs.append((adv, l, base_y + t, w, h, off) if w and h else (adv, 0, 0, 0, 0, 0))

with open(a.out, 'w') as o:
    o.write('/* generated by tools/mkfont.py from %s at %d px: NOT for the repository (derived from that font) */\n'
            % (os.path.basename(a.font), a.px))
    o.write('#define UI_FONT 1\n#define UI_FONT_FIRST 32\n#define UI_FONT_LAST 255\n')
    o.write('/* per code point: advance, x offset, y offset in the 22 px line, width, height, data offset (4 bpp, row-major, 2 px a byte) */\n')
    o.write('static const struct { signed char adv, x, y; unsigned char w, h; unsigned short off; } ui_font_g[224] = {\n')
    for g in glyphs:
        g = g if len(g) == 6 else g + (0,)
        o.write('\t{ %d, %d, %d, %d, %d, %d },\n' % g)
    o.write('};\nstatic const unsigned char ui_font_px[%d] = {\n' % max(1, len(data)))
    for i in range(0, len(data), 24):
        o.write('\t' + ', '.join(str(x) for x in data[i:i + 24]) + ',\n')
    o.write('};\n')
print('wrote %s: %d bytes of glyph data, caps %d px' % (a.out, len(data), cap_bot - cap_top))
