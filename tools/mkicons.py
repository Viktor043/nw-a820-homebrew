"""mkicons.py: the SNRGY themes' line icons (homebrew/common/snrgy_icons.h), 20x20 4-bit masks drawn here at 8x and
downsampled. Original line art in the style of the SNRGY e-reader UI. Order = home slots (screens.c home_labels)."""
import os
from PIL import Image, ImageDraw
N, S = 20, 8
OUT = os.path.join(os.path.dirname(__file__), '..', 'homebrew', 'common', 'snrgy_icons.h')

def make(kind):
    im = Image.new('L', (N * S, N * S), 0); d = ImageDraw.Draw(im)
    k = S * N / 22.0; P = lambda a, b: (a * k, b * k); w = int(1.9 * k); c = 255
    if kind == 'focus':
        d.ellipse([P(3, 4), P(19, 20)], outline=c, width=w); d.line([P(11, 7.5), P(11, 12), P(14.5, 12)], fill=c, width=w)
        d.line([P(8.5, 1.8), P(13.5, 1.8)], fill=c, width=w)
    elif kind == 'audiobook':
        d.arc([P(3, 3), P(19, 19)], 180, 360, fill=c, width=w)
        d.rounded_rectangle([P(2, 11), P(6.5, 19)], radius=2 * k, fill=c); d.rounded_rectangle([P(15.5, 11), P(20, 19)], radius=2 * k, fill=c)
    elif kind == 'podcast':
        d.rounded_rectangle([P(8, 1.5), P(14, 13)], radius=3 * k, outline=c, width=w); d.arc([P(4.5, 5.5), P(17.5, 16.5)], 0, 180, fill=c, width=w)
        d.line([P(11, 16.5), P(11, 20)], fill=c, width=w); d.line([P(7, 20.3), P(15, 20.3)], fill=c, width=w)
    elif kind == 'playing':
        d.ellipse([P(2, 2), P(20, 20)], outline=c, width=w); d.polygon([P(8.5, 6.5), P(16, 11), P(8.5, 15.5)], fill=c)
    elif kind == 'music':
        d.line([P(8, 17), P(8, 4), P(19, 2), P(19, 15)], fill=c, width=w); d.line([P(8, 6), P(19, 4)], fill=c, width=w * 2)
        for cx, cy in ((5.3, 17.3), (16.3, 15.3)): d.ellipse([P(cx - 3.2, cy - 2.6), P(cx + 3.2, cy + 2.6)], fill=c)
    elif kind == 'games':
        d.rounded_rectangle([P(1.5, 6), P(20.5, 17)], radius=5.5 * k, outline=c, width=w)
        d.line([P(5.5, 11.5), P(10, 11.5)], fill=c, width=w); d.line([P(7.75, 9.25), P(7.75, 13.75)], fill=c, width=w)
        d.ellipse([P(13.3, 8.8), P(15.7, 11.2)], fill=c); d.ellipse([P(15.8, 11.8), P(18.2, 14.2)], fill=c)
    elif kind == 'bt':
        d.line([P(6, 7), P(16, 15), P(11, 19.5), P(11, 2.5), P(16, 7), P(6, 15)], fill=c, width=w, joint='curve')
    elif kind == 'power':
        d.arc([P(3.5, 4), P(18.5, 19)], 300, 240, fill=c, width=w); d.line([P(11, 1.5), P(11, 10.5)], fill=c, width=w)
    elif kind == 'settings':
        for yy, kx in ((5, 14), (11, 7), (17, 12)):
            d.line([P(2, yy), P(20, yy)], fill=c, width=w); d.ellipse([P(kx - 2.5, yy - 2.5), P(kx + 2.5, yy + 2.5)], fill=c)
    elif kind == 'books':  # a closed book with a bookmark ribbon
        d.rounded_rectangle([P(4, 2), P(18, 20)], radius=1.5 * k, outline=c, width=w); d.line([P(7, 2.5), P(7, 19.5)], fill=c, width=w)
        d.polygon([P(12, 2), P(16, 2), P(16, 10), P(14, 8), P(12, 10)], fill=c)
    elif kind == 'order':  # in order: an arrow to the right
        d.line([P(2, 11), P(19, 11)], fill=c, width=w); d.line([P(13, 5.5), P(19, 11), P(13, 16.5)], fill=c, width=w, joint='curve')
    elif kind == 'shuffle':  # two crossing arrows
        d.line([P(2, 6), P(7, 6), P(14, 16), P(19, 16)], fill=c, width=w, joint='curve')
        d.line([P(2, 16), P(7, 16), P(14, 6), P(19, 6)], fill=c, width=w, joint='curve')
        for yy in (6, 16): d.line([P(16, yy - 3), P(19.5, yy), P(16, yy + 3)], fill=c, width=w)
    elif kind in ('repeat', 'repeat1'):  # a loop of two arrows
        d.line([P(4, 12), P(4, 6), P(18, 6)], fill=c, width=w, joint='curve'); d.line([P(15, 3), P(18.5, 6), P(15, 9)], fill=c, width=w)
        d.line([P(18, 10), P(18, 16), P(4, 16)], fill=c, width=w, joint='curve'); d.line([P(7, 13), P(3.5, 16), P(7, 19)], fill=c, width=w)
        if kind == 'repeat1': d.line([P(10, 9), P(11.5, 8), P(11.5, 13.5)], fill=c, width=int(1.6 * k))
    return [v >> 4 for v in im.resize((N, N), Image.LANCZOS).tobytes()]

kinds = ['focus', 'audiobook', 'podcast', 'playing', 'music', 'games', 'bt', 'power', 'settings',
         'order', 'shuffle', 'repeat', 'repeat1', 'books']  # 0..8 home slots, 9..12 play modes (SNRGY_ICON_MODE + mode)
with open(OUT, 'w') as o:
    o.write('/* generated by tools/mkicons.py: SNRGY line icons, %dx%d, 4 bpp (one byte per pixel, 0..15), order = home slots */\n' % (N, N))
    o.write('#define SNRGY_ICON_MODE 9\n#define SNRGY_ICON_BOOKS 13\n#define SNRGY_ICON %d\nstatic const unsigned char snrgy_icon[%d][%d] = {\n' % (N, len(kinds), N * N))
    for k in kinds:
        px = make(k); o.write('\t{ /* %s */\n' % k)
        for r in range(N): o.write('\t\t' + ','.join(str(v) for v in px[r * N:(r + 1) * N]) + ',\n')
        o.write('\t},\n')
    o.write('};\n')
print('wrote', OUT)
